// Builds the GitHub Pages site into _site/: copies the page sources in site/
// and bundles every conformance vector under spec/dataflow-graph/*/conformance
// into _site/vectors.js, so the page reads the vectors exactly as committed.
// Needs Node 18 or later and nothing else.  Run: node site/build.mjs
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(root, "_site");
const spec = join(root, "spec", "dataflow-graph");

rmSync(out, { recursive: true, force: true });
mkdirSync(out);
for (const name of readdirSync(here)) {
  if (name !== "build.mjs") cpSync(join(here, name), join(out, name), { recursive: true });
}

const parts = ["format", "semantics", "expressions", "runs"];
const vectors = Object.fromEntries(parts.map(part => {
  const dir = join(spec, part, "conformance");
  const files = readdirSync(dir).filter(n => n.endsWith(".json")).sort();
  return [part, files.map(n => JSON.parse(readFileSync(join(dir, n), "utf8")))];
}));
const versions = Object.fromEntries(parts.map(part => {
  const md = readFileSync(join(spec, part, `${part}.md`), "utf8");
  return [part, /\*\*Version:\*\*\s*([0-9.]+)/.exec(md)?.[1] ?? "?"];
}));

writeFileSync(join(out, "vectors.js"),
  `// Generated by site/build.mjs from spec/dataflow-graph/*/conformance. Do not edit.\n` +
  `window.DATAFLOW_SPEC = ${JSON.stringify({ versions, vectors }, null, 1)};\n`);

const count = parts.reduce((n, p) => n + vectors[p].length, 0);
console.log(`_site/ built: ${count} conformance vectors from ${parts.length} spec parts`);
